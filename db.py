import sqlite3

# 1) ПІДКЛЮЧЕННЯ ДО БАЗИ ДАНИХ
# Якщо файл 'shop_sqlite.db' існує — SQLite відкриє його.
# Якщо файлу немає — SQLite СТВОРИТЬ новий файл бази даних з такою назвою.
conn = sqlite3.connect('shop_sqlite.db')

# 2) СТВОРЮЄМО "CURSOR" (КУРСОР)
# Cursor — це об’єкт, через який ми виконуємо SQL-запити і отримуємо результати.
cur = conn.cursor()

# 3) ЧИТАЄМО SQL-СЦЕНАРІЙ З ФАЙЛУ
# 'orders_sqlite.sql' зазвичай містить SQL-команди типу:
# CREATE TABLE ..., INSERT INTO ..., тощо.
# encoding='utf-8' — щоб коректно читати кирилицю та спецсимволи.
with open('orders_sqlite.sql', 'r', encoding='utf-8') as f:
    sql_script = f.read()

# 4) ВИКОНУЄМО SQL-СЦЕНАРІЙ
# executescript() потрібен тоді, коли в файлі багато SQL-команд одразу,
# розділених крапкою з комою ; (наприклад CREATE TABLE + багато INSERT).
# На відміну від execute(), який виконує ОДНУ команду,
# executescript() може виконати "пакет" команд.
cur.executescript(sql_script)

# 5) ВИКОНУЄМО ЗАПИТ І ОТРИМУЄМО ДАНІ
# Тут ми беремо перші 5 рядків з таблиці orders,
# щоб перевірити, що таблиця створилась і дані завантажились.
cur.execute('''
    SELECT * 
    FROM orders 
    LIMIT 5;
''')

# fetchall() — забирає ВСІ рядки результату (тут їх максимум 5 через LIMIT).
# Повертає список кортежів: [(...), (...), ...]
rows = cur.fetchall()

# Друкуємо результат у консоль
print(rows)

# 6) ЗБЕРІГАЄМО ЗМІНИ
# commit() потрібен, якщо SQL-сценарій робив зміни в БД (CREATE/INSERT/UPDATE/DELETE).
# Без commit() зміни можуть не зберегтися (особливо якщо автокоміту немає).
conn.commit()

# 7) ЗАКРИВАЄМО З’ЄДНАННЯ
# Важливо: має бути conn.close() з дужками, інакше нічого не закриється.
conn.close()

## Коротко: що тут відбувається

'''- **connect** → відкриває або створює файл бази даних `shop_sqlite.db`
- **cursor** → “пульт керування” для виконання SQL-запитів
- **open / read** → зчитує весь SQL-код з файлу `orders_sqlite.sql`
- **executescript** → виконує багато SQL-команд підряд (CREATE, INSERT тощо)
- **SELECT … LIMIT 5** → перевірка, що таблиця існує і дані коректно завантажились
- **commit** → зберігає всі зміни в базі даних
- **close()** → закриває з’єднання з базою

## Важливий нюанс ⚠️

- `conn.close` **без дужок** → ти лише послався на функцію, але **не викликав** її  
- **Правильно:** `conn.close()` '''